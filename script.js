/* =====================================================
   VARIABLES
===================================================== */

const grid =
    document.getElementById("studentGrid");

const emptyState =
    document.getElementById("emptyState");

const searchInput =
    document.getElementById("searchInput");

const totalStudents =
    document.getElementById("totalStudents");

const navLinks =
    document.getElementById("navLinks");

const menuBtn =
    document.getElementById("menuBtn");


let currentSession = "all";


/* =====================================================
   RENDER STUDENTS
===================================================== */

function renderStudents() {

    const search =
        searchInput.value
        .toLowerCase()
        .trim();


    const filtered =
        students.filter(student => {

            const matchesSession =
                currentSession === "all" ||
                student.session === currentSession;


            const matchesSearch =
                student.name
                    .toLowerCase()
                    .includes(search)

                ||

                student.course
                    .toLowerCase()
                    .includes(search)

                ||

                student.institute
                    .toLowerCase()
                    .includes(search);


            return (
                matchesSession &&
                matchesSearch
            );

        });


    grid.innerHTML = "";


    if (filtered.length === 0) {

        emptyState.style.display =
            "block";

    } else {

        emptyState.style.display =
            "none";
    }


    filtered.forEach(
        (student, index) => {

            const card =
                document.createElement(
                    "article"
                );


            card.className =
                "student-card";


            card.style.animationDelay =
                `${index * 0.05}s`;


            card.innerHTML = `

                <div class="student-image">

                    <img
                        src="${student.image}"
                        alt="${student.name}"
                        loading="lazy"
                        onerror="
                            this.src='https://images.unsplash.com/photo-1531123897727-8f129e1688ce?auto=format&fit=crop&w=700&q=80'
                        "
                    >

                    <div class="rank">
                        🏆 ${student.rank}
                    </div>

                    <div class="session-label">
                        Session ${student.session}
                    </div>

                </div>


                <div class="student-info">

                    <h3>
                        ${student.name}
                    </h3>

                    <div class="course">
                        ${student.course}
                    </div>


                    <div class="details">

                        <div class="detail">

                            🎓

                            <span>
                                <strong>
                                    Institute:
                                </strong>
                                <br>

                                ${student.institute}
                            </span>

                        </div>


                        <div class="detail">

                            📅

                            <span>
                                <strong>
                                    Session:
                                </strong>

                                ${student.session}
                            </span>

                        </div>

                    </div>

                </div>

            `;


            grid.appendChild(card);

        }
    );


    totalStudents.textContent =
        students.length;

}


/* =====================================================
   SESSION BUTTONS
===================================================== */

document
    .querySelectorAll(".session-btn")
    .forEach(button => {

        button.addEventListener(
            "click",
            () => {

                document
                    .querySelectorAll(
                        ".session-btn"
                    )
                    .forEach(btn => {

                        btn.classList.remove(
                            "active"
                        );

                    });


                button.classList.add(
                    "active"
                );


                currentSession =
                    button.dataset.session;


                renderStudents();

            }
        );

    });


/* =====================================================
   SEARCH
===================================================== */

searchInput.addEventListener(
    "input",
    renderStudents
);


/* =====================================================
   MOBILE MENU
===================================================== */

menuBtn.addEventListener(
    "click",
    () => {

        navLinks.classList.toggle(
            "show"
        );

    }
);


/* =====================================================
   CLOSE MOBILE MENU AFTER CLICK
===================================================== */

document
    .querySelectorAll(".nav-links a")
    .forEach(link => {

        link.addEventListener(
            "click",
            () => {

                navLinks.classList.remove(
                    "show"
                );

            }
        );

    });


